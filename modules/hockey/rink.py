# modules/hockey/rink.py
"""Каток: координаты, снятые руками, прямо в коде.

Не в конфиге. Старая версия держала здесь тридцать полей и шесть кнопок
разметки — «Каток», «Ворота», «Шайба», «Ряд», «Борт», «Вратарь», — и это
окупается ровно тогда, когда каток меняется. Он не меняется: числа ниже
сняты один раз и с тех пор только перепроверялись. Так же сделан сад в
Садовнике, и по той же причине.

Числа взяты из коммита «LEGACY: хоккей — рабочая, но не идеальная версия» —
это та калибровка, на которой мод действительно играл уровень чисто.

Ряды пронумерованы сверху вниз, как на экране: ряд 1 ближе всех к воротам,
ряд 5 ближе всех к шайбе. Их пять — на большинстве уровней играют четыре,
пятый появляется на последнем.
"""
from __future__ import annotations

from dataclasses import dataclass

# Прямоугольник катка на экране: left, top, width, height.
RINK_LEFT,  RINK_TOP    = 899, 385
RINK_WIDTH, RINK_HEIGHT = 761, 652

# Створ ворот — линия, а не точка: шайба должна пересечь GOAL_Y между
# GOAL_LEFT и GOAL_RIGHT. Ворота вверху, бросок идёт снизу вверх.
GOAL_Y     = 665
GOAL_LEFT  = 1136
GOAL_RIGHT = 1409

# Откуда летит шайба.
SHOOTER = (1280, 1007)


@dataclass(frozen=True)
class Row:
    """Один ряд, по которому ездит вратарь.

    `y` — линия **шлема**: единственное, что здесь снято руками по вертикали.
    Высота полосы вокруг неё общая для всех рядов и считается ниже, потому
    что она подчиняется не ряду, а его соседям.

    `wall_left`/`wall_right` — свои у каждого ряда: каждый вратарь
    разворачивается в своём месте, общей пары бортов у катка нет. Отмечены по
    **краям** вратаря, а не по его центру.

    `body_w` — ширина вратаря. Нужна не разметке, а арифметике: борта
    отмечены по его краям, поэтому сам он ездит по отрезку короче размаха
    ряда ровно на свою ширину (см. round_trip и head_bounds).

    `feet_dy` — насколько ниже линии шлема стоят коньки. Отмечено руками
    2026-08-14, по ряду за раз: красное ищут по шлему, а мешает пролететь всё
    тело под ним, и высоту этого тела из линии шлема не вывести никак.
    """
    index: int
    y: int
    wall_left: int
    wall_right: int
    body_w: int
    feet_dy: int

    @property
    def top(self) -> int:
        return self.y - BAND_H // 2

    @property
    def bottom(self) -> int:
        return self.top + BAND_H

    @property
    def feet_y(self) -> int:
        """Экранная линия коньков."""
        return self.y + self.feet_dy

    @property
    def span(self) -> int:
        """Насколько широко ряд ездит от борта до борта."""
        return self.wall_right - self.wall_left


# feet_dy идёт вверх сверху вниз — 88, 98, 108, 116, 136 — и это не разброс
# замера, а перспектива: каток нарисован под углом, дальний вратарь мельче
# ближнего. Ровная лесенка как раз и говорит, что размечено верно.
ROWS: tuple[Row, ...] = (
    Row(0, y=574, wall_left=1056, wall_right=1495, body_w=41, feet_dy=88),
    Row(1, y=602, wall_left=1048, wall_right=1522, body_w=51, feet_dy=98),
    Row(2, y=636, wall_left=1024, wall_right=1531, body_w=63, feet_dy=108),
    Row(3, y=686, wall_left=1008, wall_right=1564, body_w=69, feet_dy=116),
    Row(4, y=738, wall_left=971,  wall_right=1606, body_w=73, feet_dy=136),
)

# ── Высота полосы ────────────────────────────────────────────────────────
# Полосы обязаны не пересекаться. Детектор теперь не разбирается, чей шлем он
# нашёл, — он считает красные пиксели внутри полосы, и красное, попавшее
# сразу в две, засчиталось бы дважды и двум разным рядам. У старой версии
# полосы перекрывались намеренно (она умела отдать общий шлем одному ряду по
# фото), и это ровно то умение, которое мы выкидываем.
#
# Поэтому высота одна на все пять и выведена, а не выбрана: берётся самый
# тесный просвет между соседними линиями шлемов и от него отступается GUARD_PX
# в обе стороны. Так пересечься полосы не могут в принципе — подвинули ряд,
# высота поехала сама.
#
# Один размер на все ряды ещё и делает счётчики красного сравнимыми между
# рядами: полоса вдвое выше набирала бы вдвое больше красного ни на чём.
GUARD_PX = 4

_TIGHTEST_GAP = min(nxt.y - cur.y for cur, nxt in zip(ROWS, ROWS[1:]))

# 20 px при нынешней калибровке: самый тесный просвет 28 (ряды 1 и 2) минус
# два отступа по 4. Шлему этого хватает с запасом — у ближнего ряда всё тело
# 123 px высотой, голова из них около двадцати.
BAND_H = _TIGHTEST_GAP - 2 * GUARD_PX

# По цвету на ряд — так пять перекрывающихся полос читаются с одного взгляда,
# а без цветов это стопка прямоугольников, в которой ничего не разобрать.
ROW_COLOURS = ("#67d3f5", "#4bdb96", "#f5b544", "#c9a6ff", "#ff8ca6")

# Полоса у борта, в которой считаются развороты. Оранжевая, потому что на
# катке больше ничего оранжевого нет.
ZONE_COLOUR = "#ff961e"

# Какую долю размаха ряда она занимает. Треть — достаточно льда, чтобы
# вратаря успели увидеть на входе и на выходе, и достаточно мало, чтобы
# большую часть заезда его в полосе не было: разворот засчитывается только
# тогда, когда видно, как он въехал и как выехал обратно.
ZONE_SHARE = 0.35


def board_zone(row: Row) -> tuple[int, int]:
    """Полоса у правого борта этого ряда — (левый край, правый край).

    Только по горизонтали: по вертикали она та же самая полоса ряда, `top`…
    `bottom`. Иначе оранжевая полоса ряда 1 залезала бы в ряд 2 и считала бы
    его красное как своё — ровно то, от чего высота полосы и выводится.

    У правого борта, а не у левого: разворот нужен один, годится любой, а
    правый у всех пяти рядов дальше от центра, то есть полоса реже цепляет
    того, кто стоит посередине.
    """
    width = round(row.span * ZONE_SHARE)
    return row.wall_right - width, row.wall_right


# Каток одним прямоугольником, в той форме, которую берёт grab_window. Кадр
# снимается один на все ряды: все пять полос лежат внутри катка, и снимать их
# по отдельности значило бы платить за захват пять раз вместо одного.
REGION = {"left": RINK_LEFT, "top": RINK_TOP,
          "width": RINK_WIDTH, "height": RINK_HEIGHT}


def zone_box(row: Row) -> tuple[int, int, int, int]:
    """Оранжевая зона внутри кадра, снятого по REGION — left, top, w, h.

    Экранные координаты минус угол катка. Отдельной функцией, потому что этим
    же прямоугольником и режут кадр, и обводят его на сохранённом снимке: два
    места, где разъехаться на пару пикселей проще всего.
    """
    left, right = board_zone(row)
    return left - RINK_LEFT, row.top - RINK_TOP, right - left, BAND_H


def row_box(row: Row) -> tuple[int, int, int, int]:
    """Вся полоса ряда от борта до борта, в координатах кадра по REGION.

    Для поиска стоячих: тот, кто не ездит, стоит где угодно между бортами, и
    смотреть на одну полосу у борта тут бессмысленно — в неё он попадёт разве
    что случайно.
    """
    return (row.wall_left - RINK_LEFT, row.top - RINK_TOP, row.span, BAND_H)


def round_trip(row: Row) -> int:
    """Сколько вратарь проезжает между двумя въездами в полосу у борта.

    Туда и обратно: въехал в полосу у правого борта, развернулся, уехал до
    левого, развернулся там и вернулся. То есть два размаха.

    Но размаха **его собственного**, а не расстояния между бортами. Борта
    отмечены по краям вратаря: прижатый к правому борту он стоит правым краем
    на `wall_right`, прижатый к левому — левым краем на `wall_left`. Значит
    любая точка на нём ездит по отрезку `span - body_w`, короче размаха ряда
    ровно на ширину самого вратаря. У ряда 1 это 398 px против 439 — десять
    процентов, которые целиком ушли бы в скорость.
    """
    return 2 * (row.span - row.body_w)


def head_bounds(row: Row) -> tuple[float, float]:
    """Отрезок, по которому ездит **голова** вратаря этого ряда.

    Не борта: те размечены по его краям, а голова сидит внутри туловища, так
    что её отрезок ýже на ширину вратаря — ровно на столько, на сколько
    round_trip короче двух размахов ряда.

    Голова считается посередине туловища. Это единственное здесь допущение, а
    не измерение: где именно шлем сидит по горизонтали, разметка не хранит.
    Пока рамку ставят «примерно туда», этого хватает; когда понадобится
    точнее, сюда приедет своё смещение.
    """
    half = row.body_w / 2
    return row.wall_left + half, row.wall_right - half
