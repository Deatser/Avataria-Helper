# modules/hockey/settings_panel.py
"""Пустая панель настроек на время переписывания мода.

У старой версии здесь было одиннадцать переключателей, из них пять скрытых
но живых: чувствительность красного, порог сверки с фото, маска разметки,
горизонт предсказания, сброс рядов, полоса у борта, автоудар, промежуточные
натяжения, рамки поверх игры и две градации логов. Каждый появлялся как
ответ на отдельную гипотезу, и вместе они перестали складываться в что-то,
что можно держать в голове.

Новая версия задумана с одним режимом, поэтому панель начинается пустой:
сюда попадёт только то, что этому режиму действительно нужно. Всё прежнее —
в коммите «LEGACY: хоккей — рабочая, но не идеальная версия».
"""
from __future__ import annotations

from PySide6.QtWidgets import QVBoxLayout

from app.ui import theme
from app.ui.sheet_panel import SheetPanel

_W = 360
_H = 240


class HockeySettingsPanel(SheetPanel):
    """Пока ничего не настраивает — держит место для нового режима."""

    def __init__(self, config, save_fn, host):
        self.config  = config
        self.save_fn = save_fn
        super().__init__(host, "НАСТРОЙКИ", (_W, _H),
                         accent=theme.HK_ICE, close_accent=theme.HK_ICE)

    def _build_body(self, layout: QVBoxLayout):
        layout.addWidget(self.caption("Мод переписывается"))
        layout.addWidget(self.hint(
            "Настроек пока нет. Старый набор — чувствительность детекции, "
            "пороги, режимы предсказания, автоудар — снят вместе с кнопками "
            "окна: новая версия делается с одним режимом, и сюда попадёт "
            "только то, что ему нужно."))
        layout.addStretch()
