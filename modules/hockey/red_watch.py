# modules/hockey/red_watch.py
"""Резкое появление красного в одной полосе — весь новый детектор целиком.

Старый разбирался, *чей* шлем он нашёл: искал красные пятна, мерил их форму
и сверял каждое с фотографиями шлема. Это нужно было только потому, что
полосы рядов перекрывались и одно пятно могло принадлежать двум рядам.
Полосы больше не перекрываются (см. rink.BAND_H), а значит вопрос «чей» отпал
вместе с ними: красное внутри полосы ряда — это вратарь этого ряда, и
считать достаточно, сколько его.

Поэтому здесь нет ни шаблонов, ни связных компонент, ни формы — одна маска по
HSV и доля закрашенных пикселей. Всё, что от неё нужно: заметить момент, когда
доля прыгнула вверх, то есть вратарь въехал в полосу.

Порог с гистерезисом, а не одно число: у одного порога доля, дрожащая вокруг
него, выдаёт десяток «появлений» на один заезд. Вошёл — когда перевалило за
ENTER_SHARE, вышел — когда упало ниже LEAVE_SHARE, и до выхода новых событий
нет.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

import cv2
import numpy as np

# Красный лежит на стыке круга оттенков, поэтому полос две, а не одна: пиксели
# шлема попадают в ту или в другую в зависимости от того, как легла тень.
_HUE_LOW  = (0, 10)
_HUE_HIGH = (170, 180)

# Насколько охотно пиксель считается красным. Числа те же, на которых работала
# старая версия («Средне» в её настройках) — они проверены на этом катке.
SAT_MIN = 120
VAL_MIN = 80

# Доли, на которых считается, что вратарь въехал и выехал. Первая прикидка, а
# не измеренная величина: полоса ряда 1 — это 154x20 пикселей, и шлем занимает
# в ней заметно больше двух процентов. Точные числа снимутся с логов — событие
# печатает долю, ради этого она там и есть.
ENTER_SHARE = 0.02
LEAVE_SHARE = 0.01

# Сколько строк под полосой разглядываются, чтобы отличить своё красное от
# чужого — см. own_red.
BELOW_PX = 6

# И насколько выше полосы может начинаться красное своего вратаря. Измерено
# по 275 пятнам во всех сохранённых кадрах: у своих верх красного отстоит от
# полосы на 0…18 px, у чужих — на 36…70. Между 19 и 35 нет ни одного пятна,
# так что порог поставлен посреди пустого зазора.
ABOVE_PX = 26

# На сколько строк выше этой черты смотрим. Чужой вратарь красный сплошь, так
# что достаточно заглянуть на пару-тройку строк — но лишний десяток стоит
# ничего и спасает от дырки в спрайте ровно на черте.
ABOVE_LOOK = 14

# Сколько строк над полосой должно быть в куске кадра, который сюда передают.
TOP_PAD = ABOVE_PX + ABOVE_LOOK

# Куда падают снимки. Внутри templates/, как просили, и каждый запуск в свою
# папку: за минуту наблюдения их набирается несколько десятков, и вместе они
# что-то значат только если понятно, к какому запуску относятся.
CATCH_ROOT = Path(__file__).resolve().parents[2] / "templates" / "red_catch"

_BOX      = (60, 255, 120)   # BGR — зелёная рамка, намеренно не красная
_BOX_PAD  = 2                # рамка рисуется снаружи зоны, не по её пикселям
_FONT       = cv2.FONT_HERSHEY_SIMPLEX
_FONT_SCALE = 0.5


def red_mask(patch: np.ndarray) -> np.ndarray:
    """Маска красных пикселей куска кадра BGR — 0 или 255."""
    hsv = cv2.cvtColor(patch, cv2.COLOR_BGR2HSV)
    low = cv2.inRange(hsv, (_HUE_LOW[0], SAT_MIN, VAL_MIN),
                            (_HUE_LOW[1], 255, 255))
    high = cv2.inRange(hsv, (_HUE_HIGH[0], SAT_MIN, VAL_MIN),
                             (_HUE_HIGH[1], 255, 255))
    return cv2.bitwise_or(low, high)


def own_red(strip: np.ndarray, band_h: int) -> np.ndarray:
    """Красное полосы, из которого выброшено чужое.

    `strip` — TOP_PAD строк над полосой, сама полоса и BELOW_PX строк под ней;
    возвращается маска размером с одну полосу.

    Зачем это нужно. Полосы рядов не пересекаются, но **вратари** — ещё как.
    Красное у вратаря идёт во весь рост: от пары десятков пикселей выше линии
    шлема и до самых коньков. Ряд 3 при росте 108 px стоит ногами на y 744, а
    полоса ряда 5 идёт 728…748 — то есть весь его низ лежит в чужой полосе.
    Живьём это стоило ряду 5 двух ложных въездов (2026-08-14, 22:11), а потом
    ещё и чужих «стоячих» (22:39).

    Отличают их две проверки, обе по столбцу.

    *Сверху.* Голова своего вратаря — это верх его красного, и он всегда
    рядом с полосой. У чужого голова далеко выше. Измерено по 275 пятнам во
    всех сохранённых кадрах: у своих верх красного выше полосы на 0…18 px, у
    чужих на 36…70, и между 19 и 35 нет ни одного пятна. Так что столбец, где
    красное есть ещё и выше ABOVE_PX, — чужой.

    *Снизу.* Красное, которое на полосе кончается, — это чей-то низ, а не
    голова. Проверено на тех же кадрах: у верных срабатываний красное тянулось
    вниз на 8…30 px, у ложных — ровно на 0.

    Первая проверка сильнее и ловит почти всё, вторая отсекает то, что вообще
    не вратарь: красную метку на льду ровно по линии шлема сверху ничем не
    отличить.
    """
    mask = red_mask(strip) > 0
    if mask.shape[0] <= TOP_PAD + band_h:
        # Кусок кадра без запаса — судить не по чему, отдаём как есть.
        return mask[:band_h]
    band = mask[TOP_PAD:TOP_PAD + band_h]
    alien = mask[:ABOVE_LOOK].any(axis=0)           # красное сильно выше
    grounded = mask[TOP_PAD + band_h:].any(axis=0)  # и есть ли что под ним
    return band & ~alien & grounded


def red_share(strip: np.ndarray, band_h: int) -> float:
    """Какая доля полосы занята **своим** красным, 0..1.

    Доля, а не количество пикселей: полосы у рядов разной ширины (154 px у
    первого, 222 у пятого), и одно и то же число закрашенных пикселей значит в
    них разное.

    Знаменатель — вся полоса, включая выброшенные столбцы: так число остаётся
    тем же, что и раньше, и пороги, снятые с прежних логов, не съезжают.
    """
    if strip is None or strip.size == 0 or band_h <= 0:
        return 0.0
    band = own_red(strip, band_h)
    return float(band.sum()) / band.size if band.size else 0.0


@dataclass(frozen=True)
class RedEvent:
    """Один въезд красного в полосу."""
    at: float        # момент по часам вызывающего
    share: float     # доля красного, на которой сработало
    before: float    # и какая была на прошлом кадре — это и есть «резко»

    @property
    def jump(self) -> float:
        return self.share - self.before


def red_centre(strip: np.ndarray, band_h: int) -> float | None:
    """Где внутри полосы своё красное — координата x его центра тяжести.

    None, если своего красного нет вовсе. Центр тяжести, а не левый край
    блоба: в полосе у борта вратарь въезжает боком, и его край — это момент, а
    середина — место. Считается по столбцам: сколько красных пикселей в
    каждом, тем и взвешивается — и по тем же столбцам, что и доля, иначе
    рамка поехала бы от чужих ног.
    """
    if strip is None or strip.size == 0 or band_h <= 0:
        return None
    columns = own_red(strip, band_h).sum(axis=0, dtype=np.int64)
    weight = int(columns.sum())
    if weight <= 0:
        return None
    return float((columns * np.arange(columns.size)).sum()) / weight


# Разрыв между столбцами, который всё ещё считается одним пятном: у шлема
# бывает светлый блик посередине, и делить его надвое из-за пары столбцов
# незачем.
BLOB_GAP = 3

# И самое узкое пятно, которое ещё может быть вратарём. Самый мелкий из них
# 41 px шириной, так что шесть — это чистый порог шума.
BLOB_MIN_W = 6


def red_blobs(strip: np.ndarray, band_h: int,
              min_apart: float = 0.0) -> list[tuple[int, int]]:
    """Пятна своего красного в полосе — (левый столбец, правый), по порядку.

    Пятнами, а не одним центром тяжести: в ряду может стоять один и ездить
    другой, и усреднить их в одну точку значит не увидеть ни того, ни другого.

    `min_apart` — насколько далеко должны стоять центры двух пятен, чтобы это
    были два разных вратаря; всё, что ближе, склеивается в одно. Передавать
    сюда надо ширину вратаря этого ряда: два вратаря не могут стоять ближе,
    чем на свою же ширину, не превратившись в одно пятно на экране.

    Без склейки один вратарь считался за двух. Его красное разорвано
    посередине — по всем сохранённым кадрам ряда 1 это ровно два пятна, и
    расстояние между их центрами держится 32 px, как бы он ни ехал: 12 px
    слева, дырка, 29 px справа. Живьём это стоило ряду 3 двух «стоячих» на
    x 1318 и x 1350 вместо одного (2026-08-14, 22:39).
    """
    if strip is None or strip.size == 0 or band_h <= 0:
        return []
    cols = np.flatnonzero(own_red(strip, band_h).any(axis=0))
    if not cols.size:
        return []
    found, start, prev = [], int(cols[0]), int(cols[0])
    for col in cols[1:]:
        col = int(col)
        if col - prev > BLOB_GAP:
            found.append((start, prev))
            start = col
        prev = col
    found.append((start, prev))
    found = [(a, b) for a, b in found if b - a + 1 >= BLOB_MIN_W]
    return _merge_close(found, min_apart)


def _merge_close(groups: list[tuple[int, int]],
                 min_apart: float) -> list[tuple[int, int]]:
    """Склеить пятна, чьи центры ближе `min_apart` друг к другу.

    Сравнивается с центром уже склеенного, а не исходного, — так вратарь,
    разорванный на три куска, собирается целиком, а не в два.
    """
    if min_apart <= 0:
        return groups
    merged: list[tuple[int, int]] = []
    for left, right in groups:
        if merged:
            was_left, was_right = merged[-1]
            if (left + right) / 2 - (was_left + was_right) / 2 < min_apart:
                merged[-1] = (was_left, right)
                continue
        merged.append((left, right))
    return merged


@dataclass(frozen=True)
class Lap:
    """Период вратаря: от первого въезда красного в полосу до второго.

    Два въезда в одну и ту же полосу — это ровно один полный цикл: между ними
    он развернулся у ближнего борта, доехал до дальнего, развернулся и
    вернулся. Поэтому `distance` — путь туда и обратно, а `seconds` — период,
    и делить одно на другое законно.

    Расстояние приходит снаружи: сколько именно проезжает вратарь, знает
    геометрия ряда (см. rink.round_trip), а этот модуль про красные пиксели.
    """
    first: float
    second: float
    distance: float

    @property
    def seconds(self) -> float:
        return self.second - self.first

    @property
    def speed(self) -> float:
        """px/с. Два въезда в один и тот же момент невозможны, но делить на
        ноль нельзя даже от невозможного."""
        return self.distance / self.seconds if self.seconds > 0 else 0.0


class RedWatch:
    """Одна полоса, за которой смотрят. Помнит ровно один бит: внутри сейчас
    красное или нет."""

    def __init__(self, band_h: int, enter: float = ENTER_SHARE,
                 leave: float = LEAVE_SHARE):
        self.band_h = int(band_h)
        self.enter = float(enter)
        self.leave = float(leave)
        self.share = 0.0          # доля на последнем показанном кадре
        self.frames = 0
        self.events = 0
        self._present = False

    def feed(self, strip: np.ndarray, at: float) -> RedEvent | None:
        """Показать полосе очередной кадр — полосу плюс BELOW_PX строк под ней.

        Возвращает событие только на **переходе** в красное — пока вратарь
        стоит в полосе, кадры идут, а событий больше нет. Иначе один заезд
        печатался бы сорок раз в секунду.
        """
        before, self.share = self.share, red_share(strip, self.band_h)
        self.frames += 1

        if self._present:
            if self.share < self.leave:
                self._present = False
            return None
        if self.share < self.enter:
            return None
        self._present = True
        self.events += 1
        return RedEvent(at=at, share=self.share, before=before)


def catch_dir(root: Path | None = None) -> Path:
    """Куда пойдут снимки этого сеанса наблюдения.

    Только считает путь и не создаёт папку: сеанс, за который красное так и не
    появилось, — обычный исход, и оставлять после каждого такого пустой
    каталог в templates/ незачем. Папку заводит save_catch, когда есть что в
    неё положить.
    """
    base = Path(root) if root is not None else CATCH_ROOT
    return base / f"{datetime.now():%Y%m%d_%H%M%S}"


def save_catch(frame: np.ndarray, zone_box: tuple[int, int, int, int],
               row_number: int, event: RedEvent, directory: Path) -> Path:
    """Кадр катка целиком с обведённой полосой — момент, на котором сработало.

    Весь каток, а не одна полоса: полоса — это 154x20 пикселей, на них не
    видно, что происходило вокруг, а вопрос к такому снимку всегда один и тот
    же — «это правда вратарь или полоса поймала что-то ещё».

    Рамка зелёная и отступает от зоны на пару пикселей: красной рамкой по
    красному детектору снимок нельзя было бы пересчитать, а рамкой по самой
    границе — можно, но она подмешалась бы в измеренные пиксели.

    Подпись латиницей: cv2 не умеет кириллицу и молча нарисует «???».
    """
    canvas = frame.copy()
    left, top, width, height = zone_box
    cv2.rectangle(canvas,
                  (left - _BOX_PAD, top - _BOX_PAD),
                  (left + width + _BOX_PAD, top + height + _BOX_PAD),
                  _BOX, 1)

    caption = (f"row {row_number}  red {event.share * 100:.1f}%  "
               f"(was {event.before * 100:.1f}%)")
    (text_w, text_h), _base = cv2.getTextSize(caption, _FONT, _FONT_SCALE, 1)
    cv2.rectangle(canvas, (2, 2), (8 + text_w, 10 + text_h), (20, 20, 20), -1)
    cv2.putText(canvas, caption, (5, 6 + text_h), _FONT, _FONT_SCALE,
                (240, 240, 240), 1, cv2.LINE_AA)

    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / (f"row{row_number}_{datetime.now():%H%M%S_%f}"
                        f"_{event.share * 100:.0f}pct.png")
    cv2.imwrite(str(path), canvas)
    return path
